"""
core/summarizer.py
────────────────────
Phase 3: Extractive Text Summarization.

This module implements two classic, 100% offline extractive summarization methods:
  1. TF-IDF Sentence Scoring — treats each sentence as a mini-document and scores
     it based on the mean TF-IDF weights of its constituent terms.
  2. Normalized Word Frequency — Luhn-style heuristic scoring that normalizes word
     counts by the maximum document frequency and penalizes empty sentences.

Important Clarifications:
  - Generative / Transformer Abstractive Summarization is NOT implemented.
    The `abstractive_summary()` function is an informational notice detailing why
    generative models were excluded (to guarantee zero hallucination and complete
    mathematical explainability for an undergraduate NLP viva).
  - ROUGE Evaluation: When evaluating a summary against the source text, ROUGE
    measures source content retention and lexical overlap. It serves as an overlap
    demonstration and is not equivalent to evaluating against a human-written gold summary.
"""

from __future__ import annotations

import collections
from dataclasses import dataclass, field
from typing import Optional

from core.text_processor import (
    clean_text,
    split_sentences,
    tokenise_words,
)


# ── Result Dataclasses ────────────────────────────────────────────────────────
@dataclass
class SentenceScore:
    """Detailed score breakdown for a single sentence."""
    index: int             # 0-based position in original document
    sentence: str          # Original sentence text
    score: float           # Computed importance score (higher = more important)
    rank: int = 0          # 1-based rank among all sentences
    selected: bool = False # Whether this sentence was chosen for the summary


@dataclass
class SummaryResult:
    """Full summarization result with metrics and explainability data."""
    summary_text: str
    selected_sentences: list[str]
    sentence_scores: list[SentenceScore]
    original_word_count: int
    summary_word_count: int
    compression_ratio: float      # e.g. 65.2% reduction
    method: str                   # 'tfidf' or 'frequency'
    num_sentences_selected: int
    total_sentences: int


# ── Method 1: Normalized Word Frequency Sentence Scoring ──────────────────────
def frequency_score_sentences(sentences: list[str]) -> list[float]:
    """
    Score sentences based on normalized word frequencies (Luhn-style approach).

    Algorithm:
      1. Tokenise words from all sentences, removing stopwords and punctuation.
      2. Calculate term frequencies across the whole document: f(w).
      3. Normalize by maximum term frequency: norm_f(w) = f(w) / max_w(f(w)).
      4. For each sentence S_i, compute its score as the average normalized
         frequency of its content words:
             Score(S_i) = sum(norm_f(w) for w in S_i) / max(1, len(content_words))
         (Normalizing by sentence length avoids biasing purely toward long sentences).

    Returns:
      List of float scores corresponding 1:1 with input sentences.
    """
    if not sentences:
        return []

    # Extract content tokens per sentence
    sent_tokens: list[list[str]] = [
        tokenise_words(s, remove_stopwords=True, remove_punct=True)
        for s in sentences
    ]

    # Calculate document-wide frequency of content words
    all_content_tokens = [t for tokens in sent_tokens for t in tokens]
    if not all_content_tokens:
        # Document contains only stopwords or punctuation: zero scores
        return [0.0] * len(sentences)

    freq_counter = collections.Counter(all_content_tokens)
    max_freq = max(freq_counter.values())

    # Normalized word weights in [0.0, 1.0]
    word_weights = {word: count / max_freq for word, count in freq_counter.items()}

    # Score each sentence
    scores: list[float] = []
    for tokens in sent_tokens:
        if not tokens:
            scores.append(0.0)
        else:
            total_weight = sum(word_weights.get(w, 0.0) for w in tokens)
            avg_score = total_weight / len(tokens)
            scores.append(round(avg_score, 4))

    return scores


# ── Method 2: TF-IDF Sentence Scoring ─────────────────────────────────────────
def tfidf_score_sentences(sentences: list[str]) -> list[float]:
    """
    Score sentences using TF-IDF vectors generated by scikit-learn.

    Algorithm:
      1. Treat each sentence as an individual document in a mini-corpus.
      2. Fit a TfidfVectorizer (with English stopwords removed).
      3. For each sentence, its score is the mean TF-IDF weight across its
         informative features.
      4. If fitting fails (e.g. empty vocabulary after stopword removal),
         gracefully falls back to normalized word frequency scoring.

    Returns:
      List of float scores corresponding 1:1 with input sentences.
    """
    if not sentences:
        return []

    try:
        from sklearn.feature_extraction.text import TfidfVectorizer

        # Filter out empty or whitespace-only strings for vectorizer
        vectorizer = TfidfVectorizer(
            stop_words="english",
            token_pattern=r"(?u)\b[a-zA-Z][a-zA-Z0-9_-]{1,}\b",
            norm="l2",
        )
        tfidf_matrix = vectorizer.fit_transform(sentences)

        scores: list[float] = []
        for i in range(len(sentences)):
            row = tfidf_matrix.getrow(i)
            data = row.data  # Non-zero TF-IDF values in this sentence
            if len(data) == 0:
                scores.append(0.0)
            else:
                # Average TF-IDF value of informative terms in sentence
                mean_tfidf = float(data.mean())
                scores.append(round(mean_tfidf, 4))

        return scores

    except (ValueError, ImportError):
        # ValueError occurs if entire vocabulary is empty or only stopwords
        return frequency_score_sentences(sentences)


# ── Core Extractive Summarizer ────────────────────────────────────────────────
def summarize_text(
    text: str,
    method: str = "tfidf",
    ratio: Optional[float] = 0.3,
    num_sentences: Optional[int] = None,
) -> SummaryResult:
    """
    Generate an extractive summary of the input text.

    Args:
      text: The source document text.
      method: 'tfidf' (default) or 'frequency'.
      ratio: Fraction of sentences to select (e.g. 0.3 for 30%).
             Used when num_sentences is None.
      num_sentences: Exact number of sentences to select (overrides ratio if set).

    Returns:
      SummaryResult containing the summary string, sentence scores, ranks,
      and compression metrics.
    """
    cleaned = clean_text(text)
    if not cleaned:
        return SummaryResult(
            summary_text="",
            selected_sentences=[],
            sentence_scores=[],
            original_word_count=0,
            summary_word_count=0,
            compression_ratio=0.0,
            method=method,
            num_sentences_selected=0,
            total_sentences=0,
        )

    sentences = split_sentences(cleaned)
    n_total = len(sentences)

    if n_total == 0:
        return SummaryResult(
            summary_text="",
            selected_sentences=[],
            sentence_scores=[],
            original_word_count=0,
            summary_word_count=0,
            compression_ratio=0.0,
            method=method,
            num_sentences_selected=0,
            total_sentences=0,
        )

    # 1. Compute raw sentence scores
    method_normalized = method.lower().strip()
    if method_normalized in ("frequency", "freq", "word_frequency"):
        scores = frequency_score_sentences(sentences)
        actual_method = "frequency"
    else:
        scores = tfidf_score_sentences(sentences)
        actual_method = "tfidf"

    # Build initial SentenceScore objects
    sentence_records = [
        SentenceScore(index=i, sentence=s, score=scores[i])
        for i, s in enumerate(sentences)
    ]

    # 2. Determine number of sentences to extract: k
    if num_sentences is not None and num_sentences > 0:
        k = min(num_sentences, n_total)
    else:
        effective_ratio = max(0.05, min(ratio if ratio is not None else 0.3, 1.0))
        k = max(1, min(n_total, int(round(n_total * effective_ratio))))

    # 3. Rank sentences by score descending, breaking ties by original index
    sorted_by_score = sorted(
        sentence_records,
        key=lambda s: (-s.score, s.index),
    )

    for rank_idx, s in enumerate(sorted_by_score, start=1):
        s.rank = rank_idx

    # 4. Select top-k sentences
    selected_indices = {s.index for s in sorted_by_score[:k]}

    for s in sentence_records:
        if s.index in selected_indices:
            s.selected = True

    # 5. Restore original document order for narrative coherence
    ordered_selected = [
        s.sentence for s in sentence_records if s.selected
    ]
    summary_text = " ".join(ordered_selected)

    # 6. Compute statistics
    orig_words = len(cleaned.split())
    summ_words = len(summary_text.split())
    compression = round((1.0 - (summ_words / max(orig_words, 1))) * 100.0, 1) if orig_words > 0 else 0.0

    return SummaryResult(
        summary_text=summary_text,
        selected_sentences=ordered_selected,
        sentence_scores=sentence_records,
        original_word_count=orig_words,
        summary_word_count=summ_words,
        compression_ratio=max(0.0, compression),
        method=actual_method,
        num_sentences_selected=len(ordered_selected),
        total_sentences=n_total,
    )


# ── Backward-Compatible Helper Function ───────────────────────────────────────
def extractive_summary(
    text: str,
    ratio: float = 0.3,
    method: str = "tfidf",
    num_sentences: Optional[int] = None,
) -> str:
    """
    Extractive summarization returning string for backward compatibility.
    """
    result = summarize_text(
        text=text,
        method=method,
        ratio=ratio,
        num_sentences=num_sentences,
    )
    return result.summary_text


